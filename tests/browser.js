(async () => {
  const results = document.querySelector('#results');
  const floating = document.querySelector('#chatgpt-vocal-button');
  const frame = () => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)));
  let failed = 0;
  let count = 0;
  function check(condition, name) {
    const li = document.createElement('li');
    li.className = condition ? 'pass' : 'fail';
    li.textContent = `${condition ? 'OK' : 'ÉCHEC'} — ${name}`;
    results.append(li);
    count++;
    if (!condition) failed++;
  }
  const state = () => floating.dataset.state;
  const click = selector => document.querySelector(selector).click();
  function space(target = document.body) {
    const event = new KeyboardEvent('keydown', { key: ' ', code: 'Space', bubbles: true, cancelable: true });
    target.dispatchEvent(event);
    return event.defaultPrevented;
  }
  await frame();
  check(floating.hidden, 'Aucun bouton avant dictée');
  click('[data-composer-voice-start]');
  await frame();
  check(floating.hidden, 'Le mode conversation vocale n’active rien');
  click('[data-dictation-button]');
  await frame();
  check(state() === 'waiting' && !floating.hidden, 'Dictée : bouton gris, ancienne réponse bloquée');
  floating.click();
  check(fixture.reads === 0, 'Clic en attente sans lecture');
  fixture.send.click();
  await frame();
  check(state() === 'generating', 'Génération : lecture indisponible');
  check(!space(), 'Espace conservé pendant la génération');
  fixture.complete(fixture.latest);
  await frame();
  check(state() === 'ready', 'Nouvelle réponse terminée : lecture disponible');
  floating.click();
  await frame();
  check(state() === 'playing' && fixture.reads === 1, 'Clic déclenche la lecture native');
  floating.click();
  await frame();
  check(state() === 'ready' && fixture.stops === 1, 'Clic interrompt la lecture native');
  check(space(), 'Espace hors contrôle déclenche la lecture');
  await frame();
  floating.click();
  await frame();
  const reads = fixture.reads;
  check(!space(document.querySelector('#input')) && fixture.reads === reads, 'Espace préservé dans un champ');
  check(!space(document.querySelector('#link')) && fixture.reads === reads, 'Espace préservé sur un lien');
  check(!space(document.querySelector('[contenteditable]')), 'Espace préservé dans le compositeur');
  // Synthetic pointer events cannot establish a native pointer capture.
  // Stub only capture; the extension’s movement/click handlers remain unchanged.
  floating.setPointerCapture = () => {};
  const pointer = (type, x, y) => floating.dispatchEvent(new PointerEvent(type, { pointerId: 1, isPrimary: true, button: 0, clientX: x, clientY: y, bubbles: true }));
  pointer('pointerdown', 20, 20);
  pointer('pointermove', 100, 100);
  check(fixture.writes === 0, 'Aucune écriture de stockage pendant le déplacement');
  pointer('pointerup', 100, 100);
  floating.dispatchEvent(new MouseEvent('click', { bubbles: true, detail: 1 }));
  check(fixture.reads === reads && fixture.writes === 1, 'Drag : pas de lecture, une écriture à la fin');
  pointer('pointerdown', 100, 100);
  pointer('pointermove', 100000, 100000);
  pointer('pointerup', 100000, 100000);
  const bounds = floating.getBoundingClientRect();
  check(bounds.right <= innerWidth && bounds.bottom <= innerHeight, 'Position limitée au viewport');
  fixture.latest.remove();
  await frame();
  check(state() === 'waiting', 'Réponse démontée : aucune substitution par l’ancienne');
  fixture.transcript.append(fixture.latest);
  await frame();
  check(state() === 'ready', 'Réponse courante remontée : lecture rétablie');
  fixture.send.click();
  check(state() === 'waiting', 'Envoi suivant : désactivation immédiate');
  await frame();
  fixture.complete(fixture.latest);
  await frame();
  check(state() === 'ready', 'Message clavier suivant : activation conservée');
  history.pushState({}, '', '/c/two');
  await frame();
  check(floating.hidden, 'Navigation interne : réinitialisation');
  history.pushState({}, '', '/');
  fixture.transcript.replaceChildren();
  fixture.transcript.setAttribute('data-chatgpt-conversation-selection-target', '');
  await frame();
  click('[data-dictation-button]');
  fixture.send.click();
  history.pushState({}, '', '/c/created');
  fixture.transcript.setAttribute('data-chatgpt-conversation-selection-target', 'created');
  await frame();
  fixture.complete(fixture.latest);
  await frame();
  check(state() === 'ready', 'Premier envoi : adoption de l’identifiant sans réinitialisation');
  const script = document.createElement('script');
  script.src = '/content.js?v=1.0.1-r3';
  await new Promise(resolve => { script.onload = resolve; document.head.append(script); });
  check(document.querySelectorAll('#chatgpt-vocal-button').length === 1, 'Réinjection : aucun bouton dupliqué');
  click('[data-dictation-button]');
  await frame();
  pointer('pointerdown', 100, 100);
  pointer('pointermove', 140, 100);
  pointer('pointerup', 140, 100);
  check(state() === 'waiting', 'Déplacement autorisé lorsque la lecture est indisponible');
  history.pushState({}, '', '/');
  await frame();
  click('[data-dictation-button]');
  await frame();
  check(!floating.hidden, 'Dictée sur la page d’accueil');
  click('#new-chat');
  await frame();
  check(floating.hidden, 'Nouvelle conversation sans changement d’URL : réinitialisation');
  const microphone = document.querySelector('[data-dictation-button]');
  microphone.setAttribute('aria-label', 'Dicter');
  const pressed = new PointerEvent('pointerdown', {
    pointerId: 4, isPrimary: true, button: 0, bubbles: true, cancelable: true,
  });
  const nativeStart = () => microphone.setAttribute('data-dictation-button', 'recording');
  microphone.addEventListener('pointerdown', nativeStart, { once: true });
  microphone.dispatchEvent(pressed);
  check(!floating.hidden && !pressed.defaultPrevented, 'Microphone français : activation avant le gestionnaire natif, sans bloquer le contrôle natif');
  microphone.click();
  await frame();
  check(state() === 'waiting', 'Dictée devenue active avant click : bouton conservé');
  click('#new-chat');
  microphone.setAttribute('data-dictation-button', 'idle');
  await frame();
  microphone.setAttribute('data-dictation-button', 'recording');
  await frame();
  check(!floating.hidden, 'Transition native idle vers enregistrement détectée sans click');
  click('#new-chat');
  microphone.setAttribute('data-dictation-button', 'idle');
  await frame();
  const key = new KeyboardEvent('keydown', { key: ' ', code: 'Space', bubbles: true, cancelable: true });
  microphone.dispatchEvent(key);
  check(!floating.hidden && !key.defaultPrevented, 'Activation clavier de la dictée française préservée');
  click('#new-chat');
  const parent = fixture.layout.parentElement;
  const sibling = fixture.layout.nextSibling;
  fixture.layout.remove();
  const standalone = document.createElement('button');
  standalone.setAttribute('data-dictation-button', 'idle');
  standalone.setAttribute('aria-label', 'Dicter');
  standalone.textContent = 'Dicter';
  document.body.append(standalone);
  standalone.click();
  await frame();
  check(!floating.hidden && state() === 'waiting', 'Apparition indépendante du conteneur spécifique de ChatGPT');
  standalone.remove();
  parent.insertBefore(fixture.layout, sibling);
  await frame();
  click('#new-chat');
  history.pushState({}, '', '/c/created');
  await frame();
  microphone.setAttribute('data-dictation-button', 'idle');
  click('[data-dictation-button]');
  fixture.send.click();
  await frame();
  fixture.complete(fixture.latest);
  await frame();
  const wasReady = state() === 'ready';
  microphone.setAttribute('data-dictation-button', 'recording');
  await frame();
  check(wasReady && state() === 'waiting', 'Nouvelle dictée native sans click : ancienne réponse immédiatement bloquée');
  click('#new-chat');
  document.querySelector('#summary').textContent = `${count - failed}/${count} tests réussis${failed ? ' — ÉCHECS' : ''}`;
  document.title = `${failed ? 'ÉCHEC' : 'OK'} — ${count - failed}/${count} tests ChatGPT Vocal`;
})();
